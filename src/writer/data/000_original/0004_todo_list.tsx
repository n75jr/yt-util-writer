function App() {
  const searchId = useId();
  const [theme, setTheme] = useState<ThemeMode>("light");
  const [dashboard, setDashboard] = useState<DashboardId>("overview");
  const [filter, setFilter] = useState<FilterId>("all");
  const [query, setQuery] = useState("");
  const deferredQuery = useDeferredValue(query);
  const [tasksState, setTasksState] = useState(tasks);
  const [activeSprintId] = useState(sprints[2].id);
  const [profileName] = useState("Niki Romanov");
  const [profileRole] = useState("Product designer & solo builder");

  useEffect(() => {
    document.documentElement.dataset.theme = theme;
  }, [theme]);

  const activeSprint = useMemo(
    () => sprints.find((sprint) => sprint.id === activeSprintId) ?? sprints[0],
    [activeSprintId],
  );

  const visibleTasks = useMemo(() => {
    const term = deferredQuery.trim().toLowerCase();
    return tasksState.filter((task) => {
      const matchesSearch =
        term.length === 0 || `${task.title} ${task.detail} ${task.assignee} ${task.tag}`.toLowerCase().includes(term);
      const matchesFilter =
        filter === "all"
          ? true
          : filter === "mine"
            ? task.assignee === "Nika"
            : filter === "urgent"
              ? task.priority === "high" || task.priority === "critical"
              : filter === "due-soon"
                ? ["Mar 1, 2026", "Mar 2, 2026", "Mar 3, 2026", "Mar 4, 2026", "Mar 5, 2026"].includes(task.due)
                : task.completed;
      const matchesDashboard = dashboard !== "focus" || task.priority === "high" || task.priority === "critical";
      return matchesSearch && matchesFilter && matchesDashboard;
    });
  }, [dashboard, deferredQuery, filter, tasksState]);

  const groupedTasks = useMemo(
    () => ({
      today: visibleTasks.filter((task) => task.column === "today"),
      upcoming: visibleTasks.filter((task) => task.column === "upcoming"),
      blocked: visibleTasks.filter((task) => task.column === "blocked"),
      done: visibleTasks.filter((task) => task.column === "done"),
    }),
    [visibleTasks],
  );

  const totals = useMemo(() => {
    const total = tasksState.length;
    const done = tasksState.filter((task) => task.completed).length;
    const urgent = tasksState.filter((task) => task.priority === "high" || task.priority === "critical").length;
    const avgProgress = Math.round(tasksState.reduce((sum, task) => sum + task.progress, 0) / Math.max(total, 1));
    return { total, done, urgent, avgProgress };
  }, [tasksState]);

  const myTasks = useMemo(() => visibleTasks.filter((task) => task.assignee === "Nika").slice(0, 6), [visibleTasks]);

  const dueSoon = useMemo(
    () => [...visibleTasks].sort((a, b) => a.due.localeCompare(b.due)).slice(0, 8),
    [visibleTasks],
  );

  const priorityMix = useMemo(
    () =>
      priorities.map((priority) => ({
        priority,
        count: visibleTasks.filter((task) => task.priority === priority).length,
      })),
    [visibleTasks],
  );

  const updateTask = (id: string, patch: Partial<Task>) => {
    startTransition(() => {
      setTasksState((current) => current.map((task) => (task.id === id ? { ...task, ...patch } : task)));
    });
  };

  const toggleDone = (task: Task) => {
    updateTask(
      task.id,
      task.completed
        ? { completed: false, column: "today", progress: 72 }
        : { completed: true, column: "done", progress: 100 },
    );
  };

  return (
    <>
      <style>{styles}</style>
      <div className="todo-shell" data-theme={theme}>
        <aside className="rail left-rail">
          <div className="profile-card solid">
            <div className="avatar">NR</div>
            <div>
              <p className="eyebrow">Profile</p>
              <h1>{profileName}</h1>
              <p className="muted">{profileRole}</p>
            </div>
          </div>
          <div className="metric-grid">
            <article className="metric-card">
              <strong>{totals.total}</strong>
              <span>tracked tasks</span>
            </article>
            <article className="metric-card">
              <strong>{totals.done}</strong>
              <span>completed</span>
            </article>
            <article className="metric-card">
              <strong>{totals.urgent}</strong>
              <span>urgent</span>
            </article>
            <article className="metric-card">
              <strong>{totals.avgProgress}%</strong>
              <span>avg progress</span>
            </article>
          </div>
          <nav className="dashboard-nav">
            {dashboards.map((item) => (
              <button
                key={item.id}
                className={item.id === dashboard ? "nav-button active" : "nav-button"}
                onClick={() => setDashboard(item.id)}
                type="button"
              >
                <strong>{item.label}</strong>
                <span>{item.detail}</span>
              </button>
            ))}
          </nav>
          <section className="flat-card">
            <div className="section-head compact">
              <div>
                <p className="eyebrow">Theme</p>
                <h3>Light / dark</h3>
              </div>
            </div>
            <div className="theme-toggle">
              <button
                className={theme === "light" ? "chip active" : "chip"}
                onClick={() => setTheme("light")}
                type="button"
              >
                Light
              </button>
              <button
                className={theme === "dark" ? "chip active" : "chip"}
                onClick={() => setTheme("dark")}
                type="button"
              >
                Dark
              </button>
            </div>
            <p className="muted small">Dark theme mirrors the same palette through inverted surface variables.</p>
          </section>
        </aside>

        <main className="main-column">
          <header className="topbar">
            <div>
              <p className="eyebrow">Flat minimal board</p>
              <h2>Tasks, profile, focus, and simple theme switching.</h2>
            </div>
            <label className="searchbox" htmlFor={searchId}>
              <span>Search</span>
              <input
                id={searchId}
                onChange={(event) => setQuery(event.target.value)}
                placeholder="Task, assignee, tag, note"
                type="search"
                value={query}
              />
            </label>
          </header>

          <section className="hero-banner">
            <div>
              <p className="eyebrow">Current sprint</p>
              <h3>{activeSprint.name}</h3>
              <p className="muted">{activeSprint.detail}</p>
            </div>
            <div className="hero-progress">
              <strong>{activeSprint.completion}%</strong>
              <div className="progress-track">
                <i style={{ width: `${activeSprint.completion}%` }} />
              </div>
            </div>
            <div className="hero-actions">
              {filters.map((item) => (
                <button
                  key={item.id}
                  className={item.id === filter ? "chip active" : "chip"}
                  onClick={() => setFilter(item.id)}
                  type="button"
                >
                  {item.label}
                </button>
              ))}
            </div>
          </section>

          <section className="board-grid">
            {columns.map((column) => (
              <article key={column} className="column-card">
                <div className="section-head">
                  <div>
                    <p className="eyebrow">Status</p>
                    <h3>{columnLabels[column]}</h3>
                  </div>
                  <span>{groupedTasks[column].length}</span>
                </div>
                <div className="task-list">
                  {groupedTasks[column].slice(0, 8).map((task) => (
                    <div key={task.id} className="task-card" style={{ borderColor: task.accent }}>
                      <div className="task-head">
                        <span className="priority-badge">{task.priority}</span>
                        <button
                          className={task.completed ? "chip active small-chip" : "chip small-chip"}
                          onClick={() => toggleDone(task)}
                          type="button"
                        >
                          {task.completed ? "Done" : "Mark done"}
                        </button>
                      </div>
                      <strong>{task.title}</strong>
                      <p className="muted">{task.detail}</p>
                      <div className="task-meta">
                        <span>{task.assignee}</span>
                        <span>{task.due}</span>
                        <span>{task.estimate}</span>
                      </div>
                      <div className="progress-track thin">
                        <i style={{ width: `${task.progress}%`, background: task.accent }} />
                      </div>
                      <div className="task-footer">
                        <span className="tag-badge">{task.tag}</span>
                        <button
                          className="text-button"
                          onClick={() => updateTask(task.id, { column: column === "blocked" ? "today" : "blocked" })}
                          type="button"
                        >
                          {column === "blocked" ? "Unblock" : "Block"}
                        </button>
                      </div>
                    </div>
                  ))}
                </div>
              </article>
            ))}
          </section>

          <section className="lower-grid">
            <article className="flat-card">
              <div className="section-head">
                <div>
                  <p className="eyebrow">My tasks</p>
                  <h3>Direct ownership</h3>
                </div>
              </div>
              <div className="stack">
                {myTasks.map((task) => (
                  <button
                    key={task.id}
                    className="list-row"
                    onClick={() => updateTask(task.id, { progress: Math.min(task.progress + 5, 100) })}
                    type="button"
                  >
                    <div>
                      <strong>{task.title}</strong>
                      <p className="muted">
                        {task.due} · {task.tag}
                      </p>
                    </div>
                    <span>{task.progress}%</span>
                  </button>
                ))}
              </div>
            </article>
            <article className="flat-card">
              <div className="section-head">
                <div>
                  <p className="eyebrow">Due soon</p>
                  <h3>Immediate follow-ups</h3>
                </div>
              </div>
              <div className="stack">
                {dueSoon.map((task) => (
                  <div key={task.id} className="list-row static-row">
                    <div>
                      <strong>{task.title}</strong>
                      <p className="muted">
                        {task.assignee} · {task.priority}
                      </p>
                    </div>
                    <span>{task.due}</span>
                  </div>
                ))}
              </div>
            </article>
          </section>
        </main>

        <aside className="rail right-rail">
          <section className="flat-card">
            <div className="section-head compact">
              <div>
                <p className="eyebrow">Tracking</p>
                <h3>Priority mix</h3>
              </div>
            </div>
            <div className="stack">
              {priorityMix.map((item, index) => (
                <div key={item.priority} className="priority-row">
                  <span>{item.priority}</span>
                  <div className="progress-track thin">
                    <i
                      style={{
                        width: `${Math.max((item.count / Math.max(visibleTasks.length, 1)) * 100, 8)}%`,
                        background: accents[index % accents.length],
                      }}
                    />
                  </div>
                  <b>{item.count}</b>
                </div>
              ))}
            </div>
          </section>
          <section className="flat-card">
            <div className="section-head compact">
              <div>
                <p className="eyebrow">Habits</p>
                <h3>Personal cadence</h3>
              </div>
            </div>
            <div className="stack">
              {habits.slice(0, 6).map((habit) => (
                <div key={habit.id} className="habit-row">
                  <div>
                    <strong>{habit.label}</strong>
                    <p className="muted">{habit.streak} day streak</p>
                  </div>
                  <span>{habit.rate}%</span>
                </div>
              ))}
            </div>
          </section>
          <section className="flat-card">
            <div className="section-head compact">
              <div>
                <p className="eyebrow">Activity</p>
                <h3>Recent changes</h3>
              </div>
            </div>
            <div className="stack">
              {activities.slice(0, 8).map((item) => (
                <article key={item.id} className="activity-row">
                  <strong>{item.title}</strong>
                  <p className="muted">{item.detail}</p>
                  <span>{item.time}</span>
                </article>
              ))}
            </div>
          </section>
          <section className="flat-card">
            <div className="section-head compact">
              <div>
                <p className="eyebrow">Notes</p>
                <h3>Tracking log</h3>
              </div>
            </div>
            <p className="muted">{trackingNotes[(visibleTasks.length * 3) % trackingNotes.length]}</p>
          </section>
        </aside>
      </div>
    </>
  );
}

